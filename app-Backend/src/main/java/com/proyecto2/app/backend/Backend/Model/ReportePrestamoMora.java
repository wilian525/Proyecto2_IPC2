package com.proyecto2.app.backend.Backend.Model;

import java.time.LocalDate;

/**
 *
 * @author wilian
 */
public class ReportePrestamoMora {
    
     private int idPrestamo;
    private int idEstudiante;
    private String estudiante;
    private int idLibro;
    private String libro;
    private LocalDate fechaPrestamo;
    private LocalDate fechaDevolucionEsperada;
    private int diasAtraso;
    private double montoMulta;

    public ReportePrestamoMora(int idPrestamo, int idEstudiante, String estudiante, int idLibro, String libro, LocalDate fechaPrestamo, LocalDate fechaDevolucionEsperada, int diasAtraso, double montoMulta) {
        this.idPrestamo = idPrestamo;
        this.idEstudiante = idEstudiante;
        this.estudiante = estudiante;
        this.idLibro = idLibro;
        this.libro = libro;
        this.fechaPrestamo = fechaPrestamo;
        this.fechaDevolucionEsperada = fechaDevolucionEsperada;
        this.diasAtraso = diasAtraso;
        this.montoMulta = montoMulta;
    }

    public int getIdPrestamo() {
        return idPrestamo;
    }

    public void setIdPrestamo(int idPrestamo) {
        this.idPrestamo = idPrestamo;
    }

    public int getIdEstudiante() {
        return idEstudiante;
    }

    public void setIdEstudiante(int idEstudiante) {
        this.idEstudiante = idEstudiante;
    }

    public String getEstudiante() {
        return estudiante;
    }

    public void setEstudiante(String estudiante) {
        this.estudiante = estudiante;
    }

    public int getIdLibro() {
        return idLibro;
    }

    public void setIdLibro(int idLibro) {
        this.idLibro = idLibro;
    }

    public String getLibro() {
        return libro;
    }

    public void setLibro(String libro) {
        this.libro = libro;
    }

    public LocalDate getFechaPrestamo() {
        return fechaPrestamo;
    }

    public void setFechaPrestamo(LocalDate fechaPrestamo) {
        this.fechaPrestamo = fechaPrestamo;
    }

    public LocalDate getFechaDevolucionEsperada() {
        return fechaDevolucionEsperada;
    }

    public void setFechaDevolucionEsperada(LocalDate fechaDevolucionEsperada) {
        this.fechaDevolucionEsperada = fechaDevolucionEsperada;
    }

    public int getDiasAtraso() {
        return diasAtraso;
    }

    public void setDiasAtraso(int diasAtraso) {
        this.diasAtraso = diasAtraso;
    }

    public double getMontoMulta() {
        return montoMulta;
    }

    public void setMontoMulta(double montoMulta) {
        this.montoMulta = montoMulta;
    }
}
